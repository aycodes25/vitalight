import { categories, products } from '../shared/catalog.js'

export const LEGACY_PRODUCT_IDS = [
  'daily-vitamins', 'vitamin-c', 'gentle-cleanser', 'first-aid-kit',
  'omega-3', 'digital-thermometer', 'oral-rehydration-salts',
]

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`
const nullable = (value) => (value === null || value === undefined ? 'null' : value)

export function buildSeedSql() {
  const categoryRows = categories
    .map((c) => `  (${quote(c.name)}, ${quote(c.description)}, ${quote(c.icon)}, ${c.sort_order})`)
    .join(',\n')

  const productRows = products
    .map((p) => `  (${[
      quote(p.id), quote(p.name), quote(p.category), quote(p.brand), quote(p.detail),
      p.price, nullable(p.oldPrice), quote(p.tag), quote(p.art), quote(p.color),
      p.stock, p.featured, p.rx_required, p.sort_order,
    ].join(', ')})`)
    .join(',\n')

  const legacyRows = LEGACY_PRODUCT_IDS
    .map((id) => {
      const p = products.find((x) => x.id === id)
      if (!p) throw new Error(`Legacy product missing from catalogue: ${id}`)
      return `  (${[quote(p.id), quote(p.brand), quote(p.detail), quote(p.tag), p.featured, p.sort_order, p.rx_required].join(', ')})`
    })
    .join(',\n')

  return `-- GENERATED by scripts/generate-seed.js from shared/catalog.js. Do not edit by hand.
-- Run after 001_catalogue_v2.sql. Re-running resets category descriptions/order and the
-- brand/detail/tag/featured/sort_order/rx_required of the 7 original products, never price,
-- stock, images or visibility.

insert into public.categories (name, description, icon, sort_order)
values
${categoryRows}
on conflict (name) do update
set description = excluded.description,
    icon = excluded.icon,
    sort_order = excluded.sort_order;

insert into public.products (id, name, category, brand, detail, price, old_price, tag, art, color, stock, featured, rx_required, sort_order)
values
${productRows}
on conflict (id) do nothing;

update public.products as p
set brand = v.brand, detail = v.detail, tag = v.tag, featured = v.featured, sort_order = v.sort_order, rx_required = v.rx_required
from (values
${legacyRows}
) as v(id, brand, detail, tag, featured, sort_order, rx_required)
where p.id = v.id;
`
}
